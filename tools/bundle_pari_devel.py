"""
Make the PARI library bundled in a repaired cypari2 wheel usable by other projects.

auditwheel (Linux) and delocate (macOS) copy libpari into the wheel, but only
after meson has written ``cypari2/pari.pc``, and they rename the library
(auditwheel) or give it an install name that cannot be linked against
(delocate). This script runs after them, as part of cibuildwheel's
``repair-wheel-command``, and

- adds the PARI headers to the wheel, as ``cypari2/pari/*.h``,
- rewrites ``cypari2/pari.pc`` to point to the bundled library and headers,
- on macOS, sets the install name of the bundled library to ``@rpath/<name>``.

Projects compiling against ``pari.pc`` then link the same libpari as cypari2.
This matters: a second copy of PARI in the same process has its own PARI stack
and global state, which leads to crashes.

Usage: python tools/bundle_pari_devel.py --include-dir <dir> <wheel or dir>
where ``<dir>/pari/pari.h`` are the headers that PARI was installed with.
"""

from __future__ import annotations

import argparse
import base64
import csv
import hashlib
import io
import re
import shutil
import subprocess
import tempfile
import zipfile
from pathlib import Path, PurePosixPath

# Where auditwheel and delocate put the bundled libraries
BUNDLED_LIBPARI = re.compile(
    r"^(?P<libdir>cypari2\.libs|cypari2/\.dylibs)/(?P<name>libpari[^/]*\.(so[^/]*|dylib))$"
)

PARI_PC = "cypari2/pari.pc"
PARI_PC_TEMPLATE = """\
# PARI library and headers bundled in this cypari2 wheel.
# Generated by tools/bundle_pari_devel.py.
prefix=${{pcfiledir}}
includedir=${{prefix}}
libdir=${{prefix}}/{libdir}

Name: pari
Description: PARI/GP library bundled with cypari2
Version: {version}
Cflags: -I${{includedir}}
Libs: ${{libdir}}/{name} -Wl,-rpath,${{libdir}}
"""


def record_hash(data: bytes) -> str:
    digest = base64.urlsafe_b64encode(hashlib.sha256(data).digest())
    return "sha256=" + digest.rstrip(b"=").decode()


def set_install_name(data: bytes, name: str) -> bytes:
    """Set the install name of a macOS dylib to ``@rpath/<name>`` and re-sign it."""
    with tempfile.TemporaryDirectory() as tmpdir:
        path = Path(tmpdir) / name
        path.write_bytes(data)
        subprocess.run(
            ["install_name_tool", "-id", f"@rpath/{name}", path], check=True
        )
        # Changing the install name invalidates the signature
        subprocess.run(["codesign", "--force", "--sign", "-", path], check=True)
        return path.read_bytes()


def bundle_pari_devel(wheel: Path, include_dir: Path) -> None:
    header_dir = include_dir / "pari"
    if not (header_dir / "pari.h").is_file():
        raise SystemExit(f"PARI headers not found in {header_dir}")

    with zipfile.ZipFile(wheel) as zin:
        infos = zin.infolist()
        contents = {info.filename: zin.read(info) for info in infos}

    libs = [m for m in map(BUNDLED_LIBPARI.match, contents) if m]
    if len(libs) != 1:
        raise SystemExit(
            f"Expected exactly one bundled PARI library in {wheel.name}, "
            f"found {[m.string for m in libs]}"
        )
    lib = libs[0]

    version = re.search(r"^Version:\s*(\S+)", contents[PARI_PC].decode(), re.M)
    if version is None:
        raise SystemExit(f"No version found in {PARI_PC}")

    updated: dict[str, bytes] = {}
    updated[PARI_PC] = PARI_PC_TEMPLATE.format(
        # relative to cypari2/, where pari.pc is
        libdir={"cypari2.libs": "../cypari2.libs", "cypari2/.dylibs": ".dylibs"}[
            lib["libdir"]
        ],
        name=lib["name"],
        version=version.group(1),
    ).encode()
    for header in sorted(header_dir.rglob("*")):
        if header.is_file():
            arcname = PurePosixPath("cypari2/pari", header.relative_to(header_dir))
            updated[str(arcname)] = header.read_bytes()
    if lib["name"].endswith(".dylib"):
        updated[lib.string] = set_install_name(contents[lib.string], lib["name"])

    record_name = next(
        name for name in contents if re.fullmatch(r"[^/]+\.dist-info/RECORD", name)
    )
    records = {
        row[0]: row
        for row in csv.reader(io.StringIO(contents[record_name].decode()))
        if row
    }
    for name, data in updated.items():
        records[name] = [name, record_hash(data), str(len(data))]
    record = io.StringIO()
    csv.writer(record, lineterminator="\n").writerows(
        row for name, row in records.items() if name != record_name
    )
    record.write(f"{record_name},,\n")
    updated[record_name] = record.getvalue().encode()

    tmp_wheel = wheel.with_suffix(".tmp")
    with zipfile.ZipFile(tmp_wheel, "w", zipfile.ZIP_DEFLATED) as zout:
        for info in infos:
            if info.filename != record_name:
                zout.writestr(info, updated.pop(info.filename, contents[info.filename]))
        record_data = updated.pop(record_name)
        for name, data in updated.items():
            info = zipfile.ZipInfo(name, date_time=infos[0].date_time)
            info.external_attr = 0o644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            zout.writestr(info, data)
        zout.writestr(next(i for i in infos if i.filename == record_name), record_data)
    shutil.move(tmp_wheel, wheel)
    print(f"Bundled PARI {version.group(1)} headers and pari.pc in {wheel.name}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--include-dir",
        type=Path,
        required=True,
        help="directory containing the pari/ directory with the PARI headers",
    )
    parser.add_argument(
        "wheels",
        type=Path,
        nargs="+",
        help="wheel files, or directories containing them",
    )
    args = parser.parse_args()
    for path in args.wheels:
        for wheel in sorted(path.glob("*.whl")) if path.is_dir() else [path]:
            bundle_pari_devel(wheel, args.include_dir)


if __name__ == "__main__":
    main()
